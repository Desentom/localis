import 'chat_message.dart';

/// Подбор истории диалога, которая поместится в контекст модели.
///
/// Без этого длинный разговор упирается в переполнение контекста: движок
/// либо обрывает ответ на середине, либо отказывается работать. Особенно
/// это заметно на слабом телефоне, где контекст пришлось ужать под память —
/// там история должна укорачиваться ещё быстрее.
///
/// Расчёт приблизительный, по символам: точно посчитать токены можно
/// только внутри движка, а вызывать его на каждый запрос ради проверки
/// дороже, чем ошибка в пару процентов.
abstract final class ChatWindow {
  /// Сколько в среднем символов приходится на один токен.
  ///
  /// Для русского текста — около трёх. Для английского было бы четыре, но
  /// приложение русскоязычное, и перестраховка в этом случае полезнее:
  /// лучше выкинуть лишнее сообщение, чем оборвать ответ.
  static const charsPerToken = 3;

  /// Запас токенов на системный промпт и служебные маркеры ChatML.
  static const promptReserve = 160;

  /// Сколько последних сообщений влезет в контекст.
  ///
  /// [reserveTokens] — сколько токенов нужно будущему ответу.
  /// Возвращённый список всегда начинается с сообщения пользователя:
  /// оборвать диалог на реплике модели («Конечно! Сейчас объясню…») хуже,
  /// чем потерять пару старых сообщений.
  static List<ChatMessage> trim({
    required List<ChatMessage> history,
    required int contextTokens,
    required int reserveTokens,
  }) {
    if (history.isEmpty) return history;

    final budget = contextTokens - reserveTokens - promptReserve;
    if (budget <= 0) {
      // Даже один вопрос не влезает — но текущий вопрос отправить
      // всё равно надо, иначе приложение выглядит сломанным.
      return [history.last];
    }

    final budgetChars = budget * charsPerToken;
    var used = 0;
    var cut = history.length;

    for (var i = history.length - 1; i >= 0; i--) {
      final cost = history[i].text.length + 8; // маркеры роли и разделители
      if (used + cost > budgetChars) break;
      used += cost;
      cut = i;
    }

    // Всё поместилось — не трогаем историю.
    if (cut == 0) return history;

    // Двигаем границу до ближайшего сообщения пользователя: оборвать
    // диалог на реплике модели («Конечно! Сейчас объясню…») хуже, чем
    // потерять пару старых сообщений.
    while (cut > 0 && !history[cut].isUser) {
      cut--;
    }
    if (cut >= history.length) cut = history.length - 1;
    if (cut == 0) return [history.last];

    return history.sublist(cut);
  }
}