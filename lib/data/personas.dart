/// Пресеты поведения. Основная ценность для школьников и вообще для
/// обычного человека — не «поговори с ней», а «получи готовый результат»:
/// разбор задачи, конспект, объяснение сложного, план подготовки.
library;

class Persona {
  const Persona({
    required this.id,
    required this.title,
    required this.emoji,
    required this.prompt,
    this.starterChips = const [],
  });

  final String id;
  final String title;
  final String emoji;

  /// Уходит в системную подсказку.
  final String prompt;

  /// Быстрые кнопки под полем ввода — то, что человек чаще всего хочет.
  final List<String> starterChips;
}

abstract final class Personas {
  static const _universal = Persona(
    id: 'default',
    title: 'Обычный',
    emoji: '💬',
    prompt:
        'Ты — понятный и честный помощник. Отвечай по-русски, кратко и по делу. '
        'Не выдумывай факты: если не знаешь или данных недостаточно, скажи об '
        'этом прямо. Если в вопросе опечатка — догадайся о смысле и уточни, '
        'если не уверен.',
    starterChips: [
      'Объясни простыми словами, что такое фотосинтез',
      'Составь план подготовки к экзамену за неделю',
      'Переведи на английский: "У меня болит голова"',
    ],
  );

  static const _homework = Persona(
    id: 'homework',
    title: 'Домашка',
    emoji: '📚',
    prompt:
        'Ты — репетитор для школьника. Объясняй по шагам, с примерами. '
        'Сначала простая идея, потом формула, потом пример. Если задача '
        'делается не в один шаг — показывай ход решения по пунктам. '
        'Не давай готовый ответ на всю домашку: подсказывай так, чтобы ученик '
        'понял и смог решить сам.',
    starterChips: [
      'Реши задачу: 3x + 7 = 22, покажи ход',
      'Объясни, почему так, если a² + b² = c²',
      'Составь план ответа на сочинение по «Войне и миру»',
    ],
  );

  static const _explain = Persona(
    id: 'explain',
    title: 'Объяснить',
    emoji: '🎓',
    prompt:
        'Ты объясняешь тему так, будто рассказываешь другу. Сначала суть в одном '
        'предложении, затем развёрнуто, затем — аналогия из обычной жизни. '
        'Используй конкретные примеры, избегай канцелярита.',
    starterChips: [
      'Объясни, как работает двигатель внутреннего сгорания',
      'Что такое фрактал простыми словами?',
      'Чем отличаются метеосводки от климата?',
    ],
  );

  static const _writing = Persona(
    id: 'writing',
    title: 'Тексты',
    emoji: '✍️',
    prompt:
        'Ты — редактор. Пиши текст, который звучит живым человеческим языком, '
        'без канцелярита и штампов. Соблюдай заданный объём и стиль. В конце '
        'кратко перечисли, что ты изменил и почему.',
    starterChips: [
      'Сократи этот текст вдвое, оставив главное',
      'Перепиши это официально, но человеческим языком',
      'Придумай заголовок к заметке о поездке',
    ],
  );

  static const _code = Persona(
    id: 'code',
    title: 'Код',
    emoji: '💻',
    prompt:
        'Ты — программист. Давай рабочий код с пояснением, что он делает. '
        'Указывай язык явно. Обрабатывай крайние случаи. Если задача неоднозначна — '
        'сначала задай один уточняющий вопрос.',
    starterChips: [
      'Напиши на Python функцию, которая делит список на чётные и нечётные',
      'Как исправить эту ошибку? (вставь код)',
      'Объясни, что делает этот SQL-запрос',
    ],
  );

  static const _translate = Persona(
    id: 'translate',
    title: 'Перевод',
    emoji: '🌍',
    prompt:
        'Ты — переводчик. Переводишь точно, сохраняя тон оригинала. '
        'После перевода давай только краткие примечания, если в тексте есть '
        'имена, термины или двусмысленность.',
    starterChips: [
      'Переведи на английский: "Мы отправляемся в поездку в субботу"',
      'Переведи на немецкий: "Собрание состоится в четверг"',
    ],
  );

  static const all = <Persona>[
    _universal,
    _homework,
    _explain,
    _writing,
    _code,
    _translate,
  ];

  static Persona byId(String id) =>
      all.firstWhere((p) => p.id == id, orElse: () => _universal);
}
